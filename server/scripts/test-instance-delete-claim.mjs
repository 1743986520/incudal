import assert from 'node:assert/strict'
import { readFile } from 'node:fs/promises'

const read = async path => (await readFile(new URL(`../${path}`, import.meta.url), 'utf8')).replace(/\r\n/g, '\n')
const route = await read('src/routes/instances.ts')
const deletion = route.slice(route.indexOf('  // 删除实例\n'), route.indexOf('  // 添加端口映射'))
assert.match(deletion, /pending: \{ requestedById: user\.id, reason \}/)
assert.match(deletion, /reply\.code\(202\)\.send\(\{ status: 'deleting'/)
assert.ok(deletion.indexOf('await claimInstanceForDelete(') < deletion.indexOf('await processPendingInstanceDeletion('))
const helpers = await read('src/routes/instances/helpers.ts')
const claim = helpers.slice(helpers.indexOf('export async function claimInstanceForDelete('), helpers.indexOf('/**', helpers.indexOf('export async function claimInstanceForDelete(')))
assert.match(claim, /currentStatus === 'deleted' \|\| currentStatus === 'deleting'/)
assert.match(claim, /tryAdvisoryTransactionLock\(tx, INSTANCE_OPERATION_LOCK_NAMESPACE, instanceId\)/)
assert.match(claim, /activeTransfer/)
assert.match(claim, /status: options\.pending \? 'deleting' : 'deleted'/)
const worker = await read('src/services/pending-instance-deletion.ts')
const remote = worker.indexOf('await ensureInstanceDeleted(')
const mark = worker.indexOf('data: { deletionRemoteDeleted: true }')
const refund = worker.indexOf('await db.settlePrivilegedDeletionBilling(')
const release = worker.indexOf('await decrementHostResourceCounters(')
assert.ok(remote >= 0 && remote < mark && mark < refund && refund < release)
assert.match(worker, /pg_try_advisory_lock/)
assert.match(worker, /deletionRemoteDeleted: true, deletionBillingPending: false/)
assert.match(worker, /deletionLastAttemptAt: \{ sort: 'asc', nulls: 'first' \}/)
assert.match(worker, /new Pool\(/)
console.log('instance delete claim regression test passed')
